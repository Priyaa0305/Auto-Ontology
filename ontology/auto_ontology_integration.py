import json
import os
from urllib.request import Request, urlopen
from urllib.error import HTTPError, URLError
from dotenv import load_dotenv
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
load_dotenv(PROJECT_DIR / ".env")

NVIDIA_BASE_URL = os.getenv("NVIDIA_AUTO_ONTOLOGY_URL","http://localhost:3001")

def get_nvidia_semantic_graph():
    """
    Retrieve the semantic entities and relationships
    generated by NVIDIA Auto Ontology.
    """
    url = (NVIDIA_BASE_URL.rstrip("/")+ "/api/exploration/semantic-graph")

    request = Request(url, headers={"Accept": "application/json"}, method="GET")

    try:
        with urlopen(request, timeout=30) as response:
            result = json.loads(response.read().decode("utf-8"))

        graph = result.get("data", result)
        return {
            "nodes": graph.get("nodes", []),
            "links": graph.get("links", [])
        }

    except HTTPError as error:
        raise RuntimeError(
            f"NVIDIA API returned HTTP {error.code}"
        ) from error

    except URLError as error:
        raise RuntimeError(
            f"Could not connect to NVIDIA Auto Ontology: "
            f"{error.reason}"
        ) from error

def get_nvidia_entities():
    """
    Return NVIDIA-generated semantic entities
    indexed by their names.
    """

    graph = get_nvidia_semantic_graph()
    entities = {}
    for node in graph["nodes"]:
        name = node.get("name")
        if name:
            entities[name] = {
                "id": node.get("id"),
                "name": name,
                "description": node.get("description", ""),
                "synonyms": node.get("synonyms", []),
                "relationship_count": node.get(
                    "relationship_count", 0
                )
            }
    return entities
if __name__ == "__main__":
    entities = get_nvidia_entities()
    print(f"NVIDIA entities retrieved: {len(entities)}")

    for name, entity in entities.items():
        print(f"\n{name}: {entity['description']}")
